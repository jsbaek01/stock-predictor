USER_SEARCH_CACHE = {}          # 실시간 중복 요청 방어벽 캐시 (5분 만료)
CACHE_EXPIRE_SECONDS = 300      # 300초

def get_cached_search(stock_name):
    """ 5분 이내 중복 검색 건에 대해 제미나이 호출 없이 메모리에서 칼반환 """
    now = time.time()
    if stock_name in USER_SEARCH_CACHE:
        cache_data = USER_SEARCH_CACHE[stock_name]
        if now < cache_data["expire_at"]:
            return cache_data["final_prediction"]
        else:
            del USER_SEARCH_CACHE[stock_name]
    return None

def set_search_cache(stock_name, prediction_text):
    """ 신규 검색 결과를 5분 타이머와 함께 메모리에 바인딩 """
    now = time.time()
    USER_SEARCH_CACHE[stock_name] = {
        "expire_at": now + CACHE_EXPIRE_SECONDS,
        "final_prediction": prediction_text
    }
